#!/usr/bin/env python3
"""把 tools/glyphs-svg/ 下的 Lucide 图标（ISC License）转成内嵌 C# 路径数据。

Lucide 图标统一为 24x24 视框、stroke-width=2、圆角端点的**描边**图形，
因此每个图标的全部子路径都按同一线宽描边渲染即可保证风格一致。

用法：python tools/gen_glyphs.py
输出：src/PlainSnip/IconGlyphs.cs
"""
import os
import re
import xml.etree.ElementTree as ET

SVG_DIR = os.path.join(os.path.dirname(os.path.abspath(__file__)), "glyphs-svg")
OUT = os.path.join(os.path.dirname(os.path.dirname(os.path.abspath(__file__))),
                   "src", "PlainSnip", "IconGlyphs.cs")

# C# 里的键名 -> SVG 文件名（均为 Lucide 图标名）
MAPPING = {
    "Move":    "move",
    "Rect":    "square",
    "Ellipse": "circle",
    "Arrow":   "arrow-up-right",
    "Pen":     "pencil",
    "Text":    "type",
    "Mosaic":  "grid-2x2",
    "Undo":    "undo-2",
    "Redo":    "redo-2",
    "Pin":     "pin",
    "Save":    "save",
    "Copy":    "copy",
    "Cancel":  "x",
}

NS = "{http://www.w3.org/2000/svg}"


def num(el, name, default=0.0):
    v = el.get(name)
    if v is None:
        return default
    m = re.match(r"-?[\d.]+", v.strip())
    return float(m.group(0)) if m else default


def fmt(v):
    s = f"{v:.3f}".rstrip("0").rstrip(".")
    return s if s not in ("-0", "") else "0"


def rect_to_path(el):
    x, y = num(el, "x"), num(el, "y")
    w, h = num(el, "width"), num(el, "height")
    rx = num(el, "rx", num(el, "ry"))
    ry = num(el, "ry", rx)
    if rx <= 0 or ry <= 0:
        return f"M{fmt(x)} {fmt(y)}H{fmt(x + w)}V{fmt(y + h)}H{fmt(x)}Z"
    return (
        f"M{fmt(x + rx)} {fmt(y)}"
        f"H{fmt(x + w - rx)}A{fmt(rx)} {fmt(ry)} 0 0 1 {fmt(x + w)} {fmt(y + ry)}"
        f"V{fmt(y + h - ry)}A{fmt(rx)} {fmt(ry)} 0 0 1 {fmt(x + w - rx)} {fmt(y + h)}"
        f"H{fmt(x + rx)}A{fmt(rx)} {fmt(ry)} 0 0 1 {fmt(x)} {fmt(y + h - ry)}"
        f"V{fmt(y + ry)}A{fmt(rx)} {fmt(ry)} 0 0 1 {fmt(x + rx)} {fmt(y)}Z"
    )


def circle_to_path(el):
    cx, cy, r = num(el, "cx"), num(el, "cy"), num(el, "r")
    return (f"M{fmt(cx - r)} {fmt(cy)}"
            f"a{fmt(r)} {fmt(r)} 0 1 0 {fmt(2 * r)} 0"
            f"a{fmt(r)} {fmt(r)} 0 1 0 {fmt(-2 * r)} 0Z")


def elem_to_path(el):
    tag = el.tag.replace(NS, "")
    if tag == "path":
        return el.get("d", "").strip()
    if tag == "rect":
        return rect_to_path(el)
    if tag == "circle":
        return circle_to_path(el)
    if tag == "line":
        return (f"M{fmt(num(el, 'x1'))} {fmt(num(el, 'y1'))}"
                f"L{fmt(num(el, 'x2'))} {fmt(num(el, 'y2'))}")
    if tag in ("polyline", "polygon"):
        pts = [float(v) for v in re.findall(r"-?[\d.]+", el.get("points", ""))]
        pairs = list(zip(pts[0::2], pts[1::2]))
        d = f"M{fmt(pairs[0][0])} {fmt(pairs[0][1])}"
        d += "".join(f"L{fmt(px)} {fmt(py)}" for px, py in pairs[1:])
        return d + ("Z" if tag == "polygon" else "")
    return ""


def load(name):
    tree = ET.parse(os.path.join(SVG_DIR, name + ".svg"))
    root = tree.getroot()
    parts = []
    for el in root.iter():
        if el is root:
            continue
        d = elem_to_path(el)
        if d:
            parts.append(d)
    return parts


def main():
    lines = [
        "// <auto-generated>",
        "//  由 tools/gen_glyphs.py 从 tools/glyphs-svg/*.svg 生成，请勿手改。",
        "//  图标来源：Lucide Icons（ISC License，https://lucide.dev/），24x24 视框、",
        "//  stroke-width=2、圆角端点，全部按描边渲染以保证风格一致。",
        "// </auto-generated>",
        "#nullable enable",
        "",
        "namespace PlainSnip;",
        "",
        "/// <summary>工具条图标路径数据：每个图标的多个子路径按 24x24 视框描述。</summary>",
        "internal static class IconGlyphs",
        "{",
        "    private static readonly Dictionary<string, string[]> Map = new(StringComparer.Ordinal)",
        "    {",
    ]
    for key, svg in MAPPING.items():
        parts = load(svg)
        if not parts:
            raise SystemExit(f"空图标：{svg}")
        lines.append(f'        ["{key}"] = new[]')
        lines.append("        {")
        for d in parts:
            lines.append(f'            "{d}",')
        lines.append("        },")
    lines += [
        "    };",
        "",
        "    public static string[]? Get(string name) => Map.TryGetValue(name, out var v) ? v : null;",
        "}",
        "",
    ]
    os.makedirs(os.path.dirname(OUT), exist_ok=True)
    with open(OUT, "w", encoding="utf-8-sig", newline="\r\n") as f:
        f.write("\n".join(lines))
    print(f"生成 {OUT}：{len(MAPPING)} 个图标")


if __name__ == "__main__":
    main()
